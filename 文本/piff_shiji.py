def normalize(files):
    """把实际文件名归一为「篇名核心」集合。
    例：'史記 白起王翦列傳.txt' → '白起王翦'
    """
    cores = set()
    for f in files:
        name = os.path.splitext(f)[0]
        name = name.replace("史記 ", "").replace("史记 ", "")
        # 去掉末尾分类词
        for cat in ["本紀", "表", "書", "世家", "列傳"]:
            if name.endswith(cat):
                name = name[: -len(cat)]
                break
        # 去掉末尾 "第X"
        name = re.sub(r'第[一二三四五六七八九十百]+$', '', name)
        cores.add(name.strip())
    return cores


def main():
    if not os.path.isdir(PIECE_DIR):
        print(f"❌ 找不到: {PIECE_DIR}")
        return

    files = [f for f in os.listdir(PIECE_DIR) if f.endswith(".txt")]
    actual = normalize(files)

    print(f"📖 《史记》缺失篇目定位")
    print(f"   实际文件: {len(files)} 篇（标准 130 篇）\n")

    # 异体字归一表（只在比对时用）
    norm_map = {
        "氂": "毛",   # 欒布 vs 欒布
        "鼂": "晁",   # 袁盎鼂錯 vs 袁盎晁錯
        "閒": "間",   # 惠景間侯者
        "遊": "游",
        "裡": "里",
    }

    def norm(text):
        for k, v in norm_map.items():
            text = text.replace(k, v)
        return text

    missing_by_cat = {}
    for cat, num, core in SHIJI:
        # 匹配：实际文件里是否存在「含此核心」的文件
        found = any(core in f or norm(core) in norm(f) for f in actual)
        # 反向：也检查核心是否被某文件"包含"
        if not found:
            for a in actual:
                if core in a or norm(core) in norm(a):
                    found = True
                    break
        if not found:
            missing_by_cat.setdefault(cat, []).append((num, core))

    if not missing_by_cat:
        print("   ✅ 130 篇齐全，无缺失！")
        return

    for cat in ["本紀", "表", "書", "世家", "列傳"]:
        if cat in missing_by_cat:
            print(f"【{cat}】缺失 {len(missing_by_cat[cat])} 篇:")
            for num, core in missing_by_cat[cat]:
                print(f"   · 第{cn_num(num)}: {core}")
            print()

    total = sum(len(v) for v in missing_by_cat.values())
    print(f"⚠️ 总计缺失 {total} 篇")


def cn_num(n):
    digits = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九']
    if n <= 10:
        return digits[n]
    if n < 20:
        return '十' + digits[n - 10]
    tens, ones = n // 10, n % 10
    return digits[tens] + '十' + (digits[ones] if ones else '')


